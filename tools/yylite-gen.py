#!/usr/bin/env python3
"""yylite-gen: emit YYLite model classes (decode init + encode) from a compact JSON spec.

Spec (JSON). Properties keep their order; keys are the JSON keys (snake_case is fine), and
Swift names are their camelCase unless "name" is given:

{
  "access": "public",                      // optional: "public" (default) or "internal"
  "models": {
    "SetInfo":  { "code": "String", "name": "String" },
    "Printing": { "year": "Int", "foil": {"type": "Bool", "default": false} },
    "Card": {
      "id": "Int", "name": "String", "mana_cost": "String?", "cmc": "Double",
      "colors": "[String]", "set": "SetInfo", "alt_set": "SetInfo?",
      "printings": "[Printing]", "power": "Int?",
      "@entry": true                       // also emit init(data:) and jsonData()
    }
  }
}

Types: Int Int64 UInt Double Float Bool String; arrays [Int] [Double] [Bool] [String];
any model name M, [M]; add "?" for optional (missing/null -> nil; nil is omitted or written as
null per JSONWriter.nilStrategy). {"type": T, "default": v} reads missing/null as v (scalars only).

Usage: yylite-gen.py spec.json -o Models.swift [--arrays map|loop] [--module-import YYLite]
"""
import argparse, json, re, sys

SCALARS = {"Int": "int", "Int64": "int64", "UInt": "uint", "Double": "double", "Float": "float",
           "Bool": "bool", "String": "string"}
ARRAYS = {"[Int]": "ints", "[Double]": "doubles", "[Bool]": "bools", "[String]": "strings"}
KEYWORDS = set("""associatedtype class deinit enum extension fileprivate func import init inout internal let open
operator private precedencegroup protocol public rethrows static struct subscript typealias var break case catch
continue default defer do else fallthrough for guard if in repeat return throw switch where while Any as await false
is nil self Self super throws true try""".split())

def camel(key):
    parts = [p for p in re.split(r"[_\-\s]+", key) if p]
    if not parts: raise SystemExit(f"bad key {key!r}")
    s = parts[0][:1].lower() + parts[0][1:] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", s): s = "_" + re.sub(r"\W", "_", s)
    return s

def ident(n): return f"`{n}`" if n in KEYWORDS else n
def lit(key): return json.dumps(key, ensure_ascii=False)        # Swift string literal (JSON escaping is valid Swift for these)

def swift_default(t, v):
    if t == "String": return lit(v)
    if t == "Bool": return "true" if v else "false"
    return repr(v)

def gen(spec, arrays):
    acc = spec.get("access", "public")
    pub = "public " if acc == "public" else ""
    models = spec["models"]
    out = ["// GENERATED by yylite-gen.py — do not edit by hand.", "#if canImport(FoundationEssentials)",
           "import FoundationEssentials", "#else", "import Foundation", "#endif", "import YYLite", ""]
    for mname, props in models.items():
        entry = bool(props.get("@entry"))
        plist = []
        for key, p in props.items():
            if key.startswith("@"): continue
            if isinstance(p, str): p = {"type": p}
            t = p["type"].replace(" ", "")
            opt = t.endswith("?"); base = t[:-1] if opt else t
            plist.append(dict(key=key, name=ident(p.get("name") or camel(key)), type=t, base=base, opt=opt,
                              default=p.get("default")))
        out.append(f"{pub}final class {mname} {{")
        for q in plist:
            out.append(f"    {pub}let {q['name']}: {q['type']}")
        out.append("")
        # ---- decode
        out.append(f"    {pub}init(_ j: JSON) throws {{")
        for q in plist:
            n, k, b, o = q["name"], lit(q["key"]), q["base"], q["opt"]
            if b in SCALARS:
                f = SCALARS[b]
                if q["default"] is not None:
                    out.append(f"        {n} = try j.{f}({k}, default: {swift_default(b, q['default'])})")
                elif o:
                    out.append(f"        {n} = try j.optional{f[0].upper() + f[1:]}({k})")
                else:
                    out.append(f"        {n} = try j.{f}({k})")
            elif b in ARRAYS:
                f = ARRAYS[b]
                out.append(f"        {n} = try j.{'optional' + f.capitalize() if o else f}({k})")
            elif b.startswith("[") and b.endswith("]"):
                m = b[1:-1]
                if m not in models: raise SystemExit(f"{mname}.{q['key']}: unknown model {m}")
                if o:
                    out.append(f"        if let a = try j.optionalObjects({k}) {{ {n} = try a.map({m}.init) }} else {{ {n} = nil }}")
                elif arrays == "map":
                    out.append(f"        {n} = try j.objects({k}).map({m}.init)")
                else:
                    out.append(f"        var _{n.strip('`')}: [{m}] = []")
                    out.append(f"        try j.forEachObject({k}) {{ _{n.strip('`')}.append(try {m}($0)) }}")
                    out.append(f"        {n} = _{n.strip('`')}")
            else:
                if b not in models: raise SystemExit(f"{mname}.{q['key']}: unknown type {b}")
                if o:
                    out.append(f"        if let o = try j.optionalObject({k}) {{ {n} = try {b}(o) }} else {{ {n} = nil }}")
                else:
                    out.append(f"        {n} = try {b}(j.object({k}))")
        out.append("    }")
        out.append("")
        # ---- encode
        out.append(f"    {pub}func encode(_ w: JSONWriter) {{")
        out.append("        w.object {")
        for q in plist:
            n, k, b, o = q["name"], lit(q["key"]), q["base"], q["opt"]
            sn = "self." + n
            if b in SCALARS:
                f = SCALARS[b]
                out.append(f"            w.{'optional' + f[0].upper() + f[1:] if o else f}({k}, {sn})")
            elif b in ARRAYS:
                f = ARRAYS[b]
                out.append(f"            w.{'optional' + f.capitalize() if o else f}({k}, {sn})")
            elif b.startswith("["):
                if o:
                    out.append(f"            if let a = {sn} {{ w.array({k}) {{ for e in a {{ e.encode(w) }} }} }} else {{ w.nilValue({k}) }}")
                else:
                    out.append(f"            w.array({k}) {{ for e in {sn} {{ e.encode(w) }} }}")
            else:
                if o:
                    out.append(f"            if let v = {sn} {{ w.key({k}); v.encode(w) }} else {{ w.nilValue({k}) }}")
                else:
                    out.append(f"            w.key({k}); {sn}.encode(w)")
        out.append("        }")
        out.append("    }")
        if entry:
            out.append("")
            out.append(f"    /// Parses `data` and decodes a {mname}.")
            out.append(f"    {pub}convenience init(data: Data) throws {{ try self.init(JSON.parse(data)) }}")
            out.append(f"    /// Encodes this {mname} as UTF-8 JSON.")
            out.append(f"    {pub}func jsonData(pretty: Bool = false) throws -> Data {{")
            out.append(f"        try JSONWriter.encode(pretty: pretty) {{ self.encode($0) }}")
            out.append("    }")
        out.append("}")
        out.append("")
    return "\n".join(out)

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("spec"); ap.add_argument("-o", "--output", default="-")
    ap.add_argument("--arrays", choices=["map", "loop"], default="map",
                    help="decode [Model] with objects().map(M.init) (default) or forEachObject + append")
    a = ap.parse_args()
    spec = json.load(open(a.spec), object_pairs_hook=dict)
    src = gen(spec, a.arrays)
    if a.output == "-": sys.stdout.write(src)
    else: open(a.output, "w").write(src)

if __name__ == "__main__":
    main()
